// Install
// ---------------------------------------------------------------------------------------------

/// Installs the three hooks, chaining with what is there. Idempotent.
///
/// # Errors
///
/// [`HooksError`] when hooks are disabled, a file cannot be read or written, or something is in
/// the way. Hooks processed before the failure stay installed; running again continues.
pub fn install(layout: &RepoLayout) -> Result<InstallReport, HooksError> {
    let location = locate(layout)?;
    fs::create_dir_all(&location.scripts_dir)
        .map_err(|e| HooksError::io("creating", &location.scripts_dir, e))?;
    let mut hooks = Vec::new();
    for name in HOOK_NAMES {
        let path = location.scripts_dir.join(name);
        let action = install_one(&location, name, &path)?;
        hooks.push(HookChange { name, path, action });
    }
    Ok(InstallReport { location, hooks })
}

fn install_one(location: &HooksLocation, name: &str, path: &Path) -> Result<Action, HooksError> {
    let runs_with_sh = location.kind == LocationKind::HuskyV9;
    match inspect(path)? {
        Existing::Missing => {
            write_new(path, &standalone(name))?;
            Ok(Action::Created)
        }
        Existing::Opaque => wrap(path, name),
        Existing::Text(text) if is_wrapper(&text) => {
            let wanted = wrapper(name);
            if text == wanted {
                Ok(Action::Unchanged)
            } else {
                write_new(path, &wanted)?;
                Ok(Action::Updated)
            }
        }
        Existing::Text(text) => {
            if !runs_with_sh && !is_shell_script(&text) {
                return wrap(path, name);
            }
            let lines: Vec<&str> = text.split_inclusive('\n').collect();
            let wanted = block(name);
            let mut out = String::with_capacity(text.len() + wanted.len());
            let action = if let Some((start, stop)) = find_block(&lines, name) {
                let current: String = lines[start..=stop].concat();
                if current == wanted {
                    return Ok(Action::Unchanged);
                }
                lines[..start].iter().for_each(|l| out.push_str(l));
                out.push_str(&wanted);
                lines[stop + 1..].iter().for_each(|l| out.push_str(l));
                Action::Updated
            } else {
                let at = injection_point(&lines);
                lines[..at].iter().for_each(|l| out.push_str(l));
                if !out.is_empty() && !out.ends_with('\n') {
                    out.push('\n');
                }
                out.push_str(&wanted);
                lines[at..].iter().for_each(|l| out.push_str(l));
                Action::Injected
            };
            fs::write(path, out).map_err(|e| HooksError::io("writing", path, e))?;
            Ok(action)
        }
    }
}

/// Moves the original aside and puts the wrapper in its place.
fn wrap(path: &Path, name: &str) -> Result<Action, HooksError> {
    let orig = orig_path(path, name);
    if fs::symlink_metadata(&orig).is_ok() {
        return Err(HooksError::Conflict {
            path: orig,
            reason: "ACS would move the existing hook there",
        });
    }
    fs::rename(path, &orig).map_err(|e| HooksError::io("moving", path, e))?;
    write_new(path, &wrapper(name))?;
    Ok(Action::Wrapped)
}

// ---------------------------------------------------------------------------------------------
// Uninstall
// ---------------------------------------------------------------------------------------------

/// Removes the ACS block from the three hooks and restores what ACS moved aside. Hooks that were
/// not installed are reported as such.
///
/// # Errors
///
/// [`HooksError`] when a file cannot be read or written.
pub fn uninstall(layout: &RepoLayout) -> Result<Vec<HookRemoval>, HooksError> {
    remove(layout, true)
}

/// What [`uninstall`] would do, without changing anything.
///
/// # Errors
///
/// [`HooksError`] when hooks are disabled or a hook file cannot be read.
pub fn uninstall_plan(layout: &RepoLayout) -> Result<Vec<HookRemoval>, HooksError> {
    remove(layout, false)
}

fn remove(layout: &RepoLayout, apply: bool) -> Result<Vec<HookRemoval>, HooksError> {
    let location = locate(layout)?;
    let mut removals = Vec::new();
    for name in HOOK_NAMES {
        let path = location.scripts_dir.join(name);
        let action = uninstall_one(name, &path, apply)?;
        removals.push(HookRemoval { name, path, action });
    }
    Ok(removals)
}

fn uninstall_one(name: &str, path: &Path, apply: bool) -> Result<RemoveAction, HooksError> {
    let orig = orig_path(path, name);
    match inspect(path)? {
        Existing::Missing => {
            if fs::symlink_metadata(&orig).is_ok() {
                if apply {
                    fs::rename(&orig, path).map_err(|e| HooksError::io("restoring", &orig, e))?;
                }
                return Ok(RemoveAction::Restored);
            }
            Ok(RemoveAction::NotInstalled)
        }
        Existing::Opaque => Ok(RemoveAction::NotInstalled),
        Existing::Text(text) => {
            let lines: Vec<&str> = text.split_inclusive('\n').collect();
            let Some((start, stop)) = find_block(&lines, name) else {
                return Ok(RemoveAction::NotInstalled);
            };
            if is_wrapper(&text) {
                if apply {
                    fs::remove_file(path).map_err(|e| HooksError::io("removing", path, e))?;
                    if fs::symlink_metadata(&orig).is_ok() {
                        fs::rename(&orig, path)
                            .map_err(|e| HooksError::io("restoring", &orig, e))?;
                    }
                }
                return Ok(RemoveAction::Restored);
            }
            let rest: Vec<&str> = lines[..start]
                .iter()
                .chain(&lines[stop + 1..])
                .copied()
                .collect();
            let only_ours = rest
                .iter()
                .all(|l| l.trim().is_empty() || l.trim_end() == "#!/bin/sh");
            if only_ours {
                if apply {
                    fs::remove_file(path).map_err(|e| HooksError::io("removing", path, e))?;
                }
                Ok(RemoveAction::Deleted)
            } else {
                if apply {
                    fs::write(path, rest.concat())
                        .map_err(|e| HooksError::io("writing", path, e))?;
                }
                Ok(RemoveAction::Removed)
            }
        }
    }
}

