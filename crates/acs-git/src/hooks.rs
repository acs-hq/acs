/// Reports the state of the three hooks without changing anything.
///
/// # Errors
///
/// [`HooksError`] when hooks are disabled or a hook file cannot be read.
pub fn status(layout: &RepoLayout) -> Result<HooksStatus, HooksError> {
    let location = locate(layout)?;
    let direct = location.kind != LocationKind::HuskyV9;
    let mut framework = matches!(
        location.kind,
        LocationKind::HuskyV9 | LocationKind::HuskyLegacy
    )
    .then_some(Framework::Husky);
    let mut hooks = Vec::new();
    for name in HOOK_NAMES {
        let path = location.scripts_dir.join(name);
        let mut entry = HookStatus {
            name,
            path: path.clone(),
            exists: false,
            installed: false,
            up_to_date: false,
            chained: false,
            active: false,
        };
        match inspect(&path)? {
            Existing::Missing => {}
            Existing::Opaque => entry.exists = true,
            Existing::Text(text) => {
                entry.exists = true;
                let lines: Vec<&str> = text.split_inclusive('\n').collect();
                if let Some((start, stop)) = find_block(&lines, name) {
                    entry.installed = true;
                    entry.up_to_date = lines[start..=stop].concat() == block(name);
                    entry.chained = if is_wrapper(&text) {
                        fs::symlink_metadata(orig_path(&path, name)).is_ok()
                    } else {
                        lines[..start].iter().chain(&lines[stop + 1..]).any(|l| {
                            let l = l.trim();
                            !l.is_empty() && !l.starts_with('#')
                        })
                    };
                }
                if text.contains("File generated by pre-commit")
                    || text.contains("https://pre-commit.com")
                {
                    framework = Some(Framework::PreCommit);
                } else if framework.is_none() && text.to_ascii_lowercase().contains("husky") {
                    framework = Some(Framework::Husky);
                }
            }
        }
        entry.active = entry.installed && (!direct || is_executable(&path));
        hooks.push(entry);
    }
    Ok(HooksStatus {
        location,
        hooks,
        framework,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shebangs_are_classified() {
        assert!(is_shell_script("#!/bin/sh\necho\n"));
        assert!(is_shell_script("#!/usr/bin/env bash\n"));
        assert!(is_shell_script("#!/usr/bin/env -S sh -e\n"));
        assert!(is_shell_script("echo no shebang\n"));
        assert!(is_shell_script(""));
        assert!(!is_shell_script("#!/usr/bin/env python3\n"));
        assert!(!is_shell_script("#!/usr/bin/env node\n"));
        assert!(!is_shell_script("#!/usr/bin/perl -w\n"));
    }

    #[test]
    fn blocks_are_found_and_versioned() {
        let text = format!("#!/bin/sh\n{}echo hi\n", block("pre-commit"));
        let lines: Vec<&str> = text.split_inclusive('\n').collect();
        let (start, stop) = find_block(&lines, "pre-commit").unwrap();
        assert_eq!(start, 1);
        assert_eq!(lines[stop].trim_end(), end_line("pre-commit"));
        assert!(find_block(&lines, "pre-push").is_none());
    }

    #[test]
    fn injection_goes_after_the_shebang_and_husky_line() {
        let lines = [
            "#!/usr/bin/env sh\n",
            ". \"$(dirname -- \"$0\")/_/husky.sh\"\n",
            "npx lint\n",
        ];
        assert_eq!(injection_point(&lines), 2);
        assert_eq!(injection_point(&["#!/bin/sh\n", "echo\n"]), 1);
        assert_eq!(injection_point(&["npm test\n"]), 0);
        assert_eq!(injection_point(&[]), 0);
    }
}
