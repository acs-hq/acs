/// Finds the hooks directory of the repository.
///
/// # Errors
///
/// [`HooksError::Disabled`] when `core.hooksPath` is `/dev/null`.
pub fn locate(layout: &RepoLayout) -> Result<HooksLocation, HooksError> {
    let configured = configured_hooks_path(layout);
    let Some(value) = configured else {
        let dir = layout.common_dir.join("hooks");
        return Ok(HooksLocation {
            kind: LocationKind::Default,
            git_hooks_dir: dir.clone(),
            scripts_dir: dir,
            configured: None,
            shared_by_worktrees: true,
        });
    };
    if value == "/dev/null" || value.eq_ignore_ascii_case("nul") {
        return Err(HooksError::Disabled(value));
    }
    let raw = Path::new(&value);
    let absolute = raw.is_absolute();
    let joined = if absolute {
        raw.to_path_buf()
    } else {
        // Relative paths are relative to the directory hooks run in: the work tree root.
        layout.work_tree.join(raw)
    };
    let dir = dunce::canonicalize(&joined).unwrap_or(joined);
    let (kind, scripts_dir) = if dir.file_name().is_some_and(|n| n == "_")
        && (dir.join("h").is_file() || dir.join("husky.sh").is_file())
        && dir.parent().is_some()
    {
        let parent = dir
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_else(|| dir.clone());
        (LocationKind::HuskyV9, parent)
    } else if dir.join("_").join("husky.sh").is_file() {
        (LocationKind::HuskyLegacy, dir.clone())
    } else {
        (LocationKind::HooksPath, dir.clone())
    };
    Ok(HooksLocation {
        kind,
        git_hooks_dir: dir,
        scripts_dir,
        configured: Some(value),
        shared_by_worktrees: absolute,
    })
}

fn configured_hooks_path(layout: &RepoLayout) -> Option<String> {
    for args in [
        &["config", "--type=path", "--get", "core.hooksPath"][..],
        &["config", "--get", "core.hooksPath"][..],
    ] {
        let Ok(output) = git_command(&layout.work_tree).args(args).output() else {
            return None;
        };
        if output.status.success() {
            let value = String::from_utf8_lossy(&output.stdout).trim().to_owned();
            return (!value.is_empty()).then_some(value);
        }
        // Exit 1 means "not set"; anything else (an old git without `--type`) is retried.
        if output.status.code() == Some(1) {
            return None;
        }
    }
    None
}

// ---------------------------------------------------------------------------------------------
// Script text
// ---------------------------------------------------------------------------------------------

fn begin_prefix(name: &str) -> String {
    format!("# >>> acs git-hook {name} >>>")
}

fn end_line(name: &str) -> String {
    format!("# <<< acs git-hook {name} <<<")
}

const CHAIN_PREFIX: &str = "# acs-chain:";

/// The ACS block of a hook: POSIX `sh`, markers included, ending in a newline.
fn block(name: &str) -> String {
    let begin = format!(
        "{} v{BLOCK_VERSION} (managed by ACS; do not edit)",
        begin_prefix(name)
    );
    let end = end_line(name);
    if name == "pre-push" {
        format!(
            "{begin}\n\
             acs_in=$(mktemp 2>/dev/null) || acs_in=\n\
             if [ -n \"$acs_in\" ] && command -v acs >/dev/null 2>&1; then\n\
             \x20 cat >\"$acs_in\"\n\
             \x20 acs_rc=0\n\
             \x20 acs git-hook {name} \"$@\" <\"$acs_in\" || acs_rc=$?\n\
             \x20 exec <\"$acs_in\"\n\
             \x20 rm -f \"$acs_in\" || :\n\
             \x20 [ \"$acs_rc\" -eq 0 ] || exit \"$acs_rc\"\n\
             else\n\
             \x20 [ -z \"$acs_in\" ] || rm -f \"$acs_in\" || :\n\
             \x20 echo \"acs: the ACS git backstop ({name}) did not run (acs not found on PATH)\" >&2\n\
             fi\n\
             unset acs_in acs_rc\n\
             {end}\n"
        )
    } else {
        format!(
            "{begin}\n\
             if command -v acs >/dev/null 2>&1; then\n\
             \x20 acs git-hook {name} \"$@\" || exit $?\n\
             else\n\
             \x20 echo \"acs: the ACS git backstop ({name}) did not run (acs not found on PATH)\" >&2\n\
             fi\n\
             {end}\n"
        )
    }
}

fn standalone(name: &str) -> String {
    format!("#!/bin/sh\n{}", block(name))
}

fn wrapper(name: &str) -> String {
    format!(
        "#!/bin/sh\n{}{CHAIN_PREFIX} the original hook was moved to {name}.acs-orig\n\
         exec \"$(dirname \"$0\")/{name}.acs-orig\" \"$@\"\n",
        block(name)
    )
}

fn is_wrapper(text: &str) -> bool {
    text.lines().any(|l| l.starts_with(CHAIN_PREFIX))
}

/// The line range `[start, end]` (inclusive) of the ACS block in `lines`.
fn find_block(lines: &[&str], name: &str) -> Option<(usize, usize)> {
    let prefix = begin_prefix(name);
    let end = end_line(name);
    let start = lines.iter().position(|l| l.starts_with(&prefix))?;
    let stop = lines[start..]
        .iter()
        .position(|l| l.trim_end() == end)
        .map(|i| start + i)?;
    Some((start, stop))
}

/// Whether the file's text is a script a block can be inserted into.
fn is_shell_script(text: &str) -> bool {
    let Some(first) = text.lines().next().filter(|l| l.starts_with("#!")) else {
        return true;
    };
    let base = |word: &str| word.rsplit(['/', '\\']).next().unwrap_or(word).to_owned();
    let mut words = first[2..].split_whitespace();
    let Some(program) = words.next().map(base) else {
        return false;
    };
    let program = if program == "env" {
        match words.find(|w| !w.starts_with('-') && !w.contains('=')) {
            Some(word) => base(word),
            None => return false,
        }
    } else {
        program
    };
    matches!(
        program.as_str(),
        "sh" | "bash" | "dash" | "ash" | "zsh" | "ksh" | "mksh" | "busybox"
    )
}

/// The line index where the block goes: after the shebang, and after a `husky.sh` line near the
/// top (so `HUSKY=0` still turns the hooks off before ACS runs).
fn injection_point(lines: &[&str]) -> usize {
    let after_shebang = usize::from(lines.first().is_some_and(|l| l.starts_with("#!")));
    let window_end = lines.len().min(after_shebang + 4);
    lines[after_shebang..window_end]
        .iter()
        .rposition(|l| l.contains("husky.sh"))
        .map_or(after_shebang, |i| after_shebang + i + 1)
}

