fn orig_path(path: &Path, name: &str) -> PathBuf {
    path.with_file_name(format!("{name}.acs-orig"))
}

fn write_new(path: &Path, text: &str) -> Result<(), HooksError> {
    fs::write(path, text).map_err(|e| HooksError::io("writing", path, e))?;
    set_executable(path)
}

#[cfg(unix)]
fn set_executable(path: &Path) -> Result<(), HooksError> {
    use std::os::unix::fs::PermissionsExt;
    fs::set_permissions(path, fs::Permissions::from_mode(0o755))
        .map_err(|e| HooksError::io("making executable", path, e))
}

#[cfg(not(unix))]
fn set_executable(_path: &Path) -> Result<(), HooksError> {
    Ok(())
}

#[cfg(unix)]
fn is_executable(path: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    fs::metadata(path).is_ok_and(|m| m.permissions().mode() & 0o111 != 0)
}

#[cfg(not(unix))]
fn is_executable(_path: &Path) -> bool {
    true
}

/// What is at a hook path.
enum Existing {
    Missing,
    /// A regular UTF-8 text file.
    Text(String),
    /// A symlink, a binary file, or anything else that cannot be edited as text.
    Opaque,
}

fn inspect(path: &Path) -> Result<Existing, HooksError> {
    let meta = match fs::symlink_metadata(path) {
        Ok(meta) => meta,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(Existing::Missing),
        Err(e) => return Err(HooksError::io("reading", path, e)),
    };
    if meta.is_dir() {
        return Err(HooksError::Conflict {
            path: path.to_path_buf(),
            reason: "it is a directory",
        });
    }
    if meta.file_type().is_symlink() {
        return Ok(Existing::Opaque);
    }
    let bytes = fs::read(path).map_err(|e| HooksError::io("reading", path, e))?;
    Ok(String::from_utf8(bytes).map_or(Existing::Opaque, Existing::Text))
}

