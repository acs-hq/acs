//! Installing the ACS git hooks (`pre-commit`, `prepare-commit-msg`, `pre-push`) so that they
//! **chain** with whatever is already there and never overwrite it.
//!
//! The hooks are small POSIX `sh` that run `acs git-hook <name> "$@"` and then let the original
//! hook, if any, run. If `acs` is not on `PATH` they print one line and let git proceed: the
//! backstop fails open (the gate itself is the hook pipeline).
//!
//! # Where hooks live
//!
//! [`locate`] finds the directory git runs hooks from and the directory ACS edits:
//!
//! | Layout | Detected by | Git runs | ACS edits |
//! | --- | --- | --- | --- |
//! | default | `core.hooksPath` unset | `<common git dir>/hooks` (shared by all worktrees) | the same |
//! | custom | `core.hooksPath` set (absolute, `~`, or relative to the work tree root) | that directory | the same |
//! | husky 9 | `core.hooksPath` ends in `_` and holds husky's runner `h` (or `husky.sh`) | `.husky/_/<hook>`, regenerated by `husky` | the user scripts in the parent, `.husky/<hook>` |
//! | husky 5 to 8 | `<hooksPath>/_/husky.sh` exists | `.husky/<hook>` | the same |
//!
//! Husky 4 and the pre-commit framework write plain scripts into `.git/hooks`, so they are the
//! default layout; the framework is recognised from its header for [`status`].
//!
//! # How a hook is chained
//!
//! - **No hook yet**: a new executable script holding the ACS block.
//! - **A shell script** (shebang `sh`, `bash`, `dash`, `zsh`, `ksh`, ..., or none; always for
//!   husky, which runs scripts with `sh`): the ACS block is **inserted after the shebang** (and
//!   after husky's `husky.sh` line), between two marker comments. The original text is untouched,
//!   so removing the block restores it byte for byte. The pre-commit framework's script and
//!   husky's user scripts are handled this way.
//! - **Anything else** (a Python or Node script, a binary, a symlink): the original is renamed to
//!   `<hook>.acs-orig` and a wrapper that runs the block and then `exec`s the original takes its
//!   place. [`uninstall`] puts it back.
//!
//! Installing is idempotent: a block that is already current is left alone, an outdated one is
//! replaced. Tools that regenerate their hook files (`husky`, `pre-commit install`) drop the
//! block; [`status`] shows it and installing again puts it back.
//!
//! `pre-push` receives the refs to push on stdin, which the original hook may need too, so the
//! block buffers stdin in a temporary file and gives it back to the rest of the script.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::RepoLayout;
use crate::repo::git_command;

pub mod query;

/// The hooks ACS installs.
pub const HOOK_NAMES: [&str; 3] = ["pre-commit", "prepare-commit-msg", "pre-push"];

/// Version of the block text; a different version is replaced on install.
const BLOCK_VERSION: u32 = 1;

/// Why installing, removing or inspecting hooks failed.
#[derive(Debug, thiserror::Error)]
pub enum HooksError {
    /// A filesystem operation failed.
    #[error("{action} {}: {source}", .path.display())]
    Io {
        /// What was being attempted.
        action: &'static str,
        /// The path involved.
        path: PathBuf,
        /// The underlying error.
        #[source]
        source: io::Error,
    },
    /// `core.hooksPath` points at `/dev/null` (or `NUL`): the person turned hooks off.
    #[error("git hooks are disabled in this repository (core.hooksPath is {0})")]
    Disabled(String),
    /// A file is where ACS needs to put one.
    #[error("{} is in the way: {reason}", .path.display())]
    Conflict {
        /// The path.
        path: PathBuf,
        /// What is wrong with it.
        reason: &'static str,
    },
}

impl HooksError {
    fn io(action: &'static str, path: &Path, source: io::Error) -> Self {
        Self::Io {
            action,
            path: path.to_path_buf(),
            source,
        }
    }
}

/// How the repository's hooks are laid out.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LocationKind {
    /// `<common git dir>/hooks`, shared by every worktree.
    Default,
    /// A directory named by `core.hooksPath`.
    HooksPath,
    /// husky 9: git runs generated stubs in `.husky/_`, which run the user scripts in `.husky`.
    HuskyV9,
    /// husky 5 to 8: `core.hooksPath` is `.husky`, whose scripts source `_/husky.sh`.
    HuskyLegacy,
}

/// The hooks directory of a repository.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HooksLocation {
    /// The layout.
    pub kind: LocationKind,
    /// The directory git looks in.
    pub git_hooks_dir: PathBuf,
    /// The directory ACS reads and writes hook files in (differs from `git_hooks_dir` for
    /// husky 9).
    pub scripts_dir: PathBuf,
    /// The value of `core.hooksPath`, when set.
    pub configured: Option<String>,
    /// Whether every worktree of the repository runs these same files.
    pub shared_by_worktrees: bool,
}

/// A hook framework recognised in the repository.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Framework {
    /// husky.
    Husky,
    /// The pre-commit framework (pre-commit.com).
    PreCommit,
}

/// What [`install`] did to one hook.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Action {
    /// There was no hook; a new one holds the ACS block.
    Created,
    /// The block was inserted into the existing shell script.
    Injected,
    /// The existing hook was moved to `<hook>.acs-orig` and a wrapper installed.
    Wrapped,
    /// An outdated block or wrapper was replaced.
    Updated,
    /// Already current; nothing changed.
    Unchanged,
}

/// What [`install`] did to one hook file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HookChange {
    /// The hook name.
    pub name: &'static str,
    /// The file.
    pub path: PathBuf,
    /// What happened.
    pub action: Action,
}

/// The result of [`install`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstallReport {
    /// Where the hooks are.
    pub location: HooksLocation,
    /// One entry per hook of [`HOOK_NAMES`].
    pub hooks: Vec<HookChange>,
}

impl InstallReport {
    /// Whether anything on disk changed.
    #[must_use]
    pub fn changed(&self) -> bool {
        self.hooks.iter().any(|h| h.action != Action::Unchanged)
    }
}

/// What [`uninstall`] did to one hook.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RemoveAction {
    /// The block was cut out of a script that has other content.
    Removed,
    /// The file held only ACS content and was deleted.
    Deleted,
    /// A wrapper was deleted and the original moved back.
    Restored,
    /// ACS was not installed in this hook.
    NotInstalled,
}

/// What [`uninstall`] did to one hook file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HookRemoval {
    /// The hook name.
    pub name: &'static str,
    /// The file.
    pub path: PathBuf,
    /// What happened.
    pub action: RemoveAction,
}

/// The state of one hook (see [`status`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HookStatus {
    /// The hook name.
    pub name: &'static str,
    /// The file ACS manages (`<scripts dir>/<name>`).
    pub path: PathBuf,
    /// Whether that file exists.
    pub exists: bool,
    /// Whether it holds the ACS block (or is the ACS wrapper).
    pub installed: bool,
    /// Whether the block is the current version.
    pub up_to_date: bool,
    /// Whether another hook runs after the block: the script's own content, or an original
    /// moved aside.
    pub chained: bool,
    /// Whether git will actually run it (a hook git executes directly must be executable).
    pub active: bool,
}

/// The result of [`status`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HooksStatus {
    /// Where the hooks are.
    pub location: HooksLocation,
    /// One entry per hook of [`HOOK_NAMES`].
    pub hooks: Vec<HookStatus>,
    /// The hook framework found, if any.
    pub framework: Option<Framework>,
}

impl HooksStatus {
    /// Whether every hook is installed, current and active.
    #[must_use]
    pub fn healthy(&self) -> bool {
        self.hooks
            .iter()
            .all(|h| h.installed && h.up_to_date && h.active)
    }
}

